type watchdogCheck struct {
	ID     string `json:"id"`
	Name   string `json:"name"`
	Status string `json:"status"`
	Detail string `json:"detail"`
	Action string `json:"action"`
	Href   string `json:"href"`
}

type watchdogReport struct {
	CheckedAt time.Time       `json:"checkedAt"`
	Status    string          `json:"status"`
	Checks    []watchdogCheck `json:"checks"`
}

type Watchdog struct {
	mu       sync.RWMutex
	report   watchdogReport
	failures map[string]watchdogHTTPFailure
}

type watchdogHTTPFailure struct {
	method string
	route  string
	status int
	count  int
	last   time.Time
}

func (watchdog *Watchdog) recordHTTP(c *gin.Context) {
	defer func() {
		status, route := c.Writer.Status(), c.FullPath()
		if status < 500 || route == "" {
			return
		}
		watchdog.mu.Lock()
		defer watchdog.mu.Unlock()
		if watchdog.failures == nil {
			watchdog.failures = make(map[string]watchdogHTTPFailure)
		}
		for key, failure := range watchdog.failures {
			if time.Since(failure.last) > 24*time.Hour {
				delete(watchdog.failures, key)
			}
		}
		key := fmt.Sprintf("%s %s %d", c.Request.Method, route, status)
		failure := watchdog.failures[key]
		if len(watchdog.failures) >= 50 && failure.count == 0 {
			var oldestKey string
			var oldest time.Time
			for existingKey, existing := range watchdog.failures {
				if oldest.IsZero() || existing.last.Before(oldest) {
					oldestKey, oldest = existingKey, existing.last
				}
			}
			delete(watchdog.failures, oldestKey)
		}
		watchdog.failures[key] = watchdogHTTPFailure{method: c.Request.Method, route: route, status: status, count: failure.count + 1, last: time.Now().UTC()}
	}()
	c.Next()
}

func StartWatchdog(ctx context.Context, database *sql.DB, config app.Config) *Watchdog {
	watchdog := &Watchdog{report: watchdogReport{Status: "unknown", Checks: []watchdogCheck{
		{ID: "watchdog", Name: "Watchdog", Status: "unknown", Detail: "Waiting for the first server check.", Href: "/settings/watchdog"},
	}}}
	server := &apiServer{db: database, config: config}
	go watchdog.run(ctx, time.Minute, server.collectWatchdog)
	return watchdog
}

func (watchdog *Watchdog) run(ctx context.Context, interval time.Duration, collect func(context.Context) watchdogReport) {
	ticker := time.NewTicker(interval)
	defer ticker.Stop()
	for {
		if ctx.Err() != nil {
			return
		}
		report := collect(ctx)
		watchdog.mu.Lock()
		watchdog.report = report
		watchdog.mu.Unlock()
		select {
		case <-ctx.Done():
			return
		case <-ticker.C:
		}
	}
}

func (watchdog *Watchdog) snapshot() watchdogReport {
	watchdog.mu.RLock()
	report := watchdog.report
	report.Checks = append([]watchdogCheck{}, report.Checks...)
	keys := make([]string, 0, len(watchdog.failures))
	for key := range watchdog.failures {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	for _, key := range keys {
		failure := watchdog.failures[key]
		if time.Since(failure.last) > 24*time.Hour {
			continue
		}
		report.Status = "error"
		report.Checks = append(report.Checks, watchdogCheck{ID: "http-" + key, Name: "Backend request failure", Status: "error", Detail: fmt.Sprintf("%s %s returned HTTP %d (%d observed failures; last %s).", failure.method, failure.route, failure.status, failure.count, failure.last.Format(time.RFC3339)), Action: "Review backend logs and retry only safe reads. Recent failures remain visible for 24 hours; up to 50 groups are retained until backend restart.", Href: "/settings/watchdog"})
	}
	watchdog.mu.RUnlock()
	if !report.CheckedAt.IsZero() && time.Since(report.CheckedAt) > 2*time.Minute {
		report.Status = "error"
		report.Checks = append(report.Checks, watchdogCheck{ID: "watchdog-stale", Name: "Watchdog freshness", Status: "error", Detail: "No completed server check in more than two minutes.", Action: "Check backend availability and server logs.", Href: "/settings/watchdog"})
	}
	return report
}

func (server *apiServer) collectWatchdog(ctx context.Context) watchdogReport {
	ctx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	report := watchdogReport{CheckedAt: time.Now().UTC(), Status: "ok", Checks: []watchdogCheck{
		{ID: "backend", Name: "Backend", Status: "ok", Detail: "Watchdog report generated by the backend.", Href: "/settings"},
	}}
	add := func(check watchdogCheck) {
		report.Checks = append(report.Checks, check)
		if check.Status == "error" || (check.Status == "warning" && report.Status != "error") || (check.Status == "unknown" && report.Status == "ok") {
			report.Status = check.Status
		}
	}
	if err := server.db.PingContext(ctx); err != nil {
		add(watchdogCheck{ID: "database", Name: "Database", Status: "error", Detail: "Database did not respond to the health check.", Action: "Check database service, connectivity and server logs.", Href: "/settings"})
	} else {
		add(watchdogCheck{ID: "database", Name: "Database", Status: "ok", Detail: "Database connection responded.", Href: "/settings"})
		var total, stale, unknown, unlinked int
		err := server.db.QueryRowContext(ctx, `SELECT COUNT(*),
			COUNT(*) FILTER (WHERE last_heartbeat_at <= NOW() - INTERVAL '90 seconds'),
			COUNT(*) FILTER (WHERE last_heartbeat_at IS NULL OR last_heartbeat_at > NOW()),
			COUNT(*) FILTER (WHERE NULLIF(TRIM(salt_minion_id), '') IS NULL)
			FROM assets WHERE is_compute = TRUE`).Scan(&total, &stale, &unknown, &unlinked)
		if err != nil {
			add(watchdogCheck{ID: "devices", Name: "Device reporting", Status: "error", Detail: "Device health records could not be read.", Action: "Check database migrations and server logs.", Href: "/devices"})
		} else {
			status := "ok"
			if total == 0 || stale+unknown+unlinked > 0 {
				status = "warning"
			}
			add(watchdogCheck{ID: "devices", Name: "Device reporting", Status: status,
				Detail: fmt.Sprintf("%d computers; %d stale heartbeats; %d unknown heartbeats; %d without a Salt identity. Heartbeats do not verify SSH or Salt connectivity.", total, stale, unknown, unlinked),
				Action: "Review offline or unknown devices and their agent connection.", Href: "/devices"})
		}
		rows, err := server.db.QueryContext(ctx, `SELECT al.source, COALESCE(al.device_id::text, ''), COALESCE(a.asset_tag, ''), COUNT(*)
			FROM alerts al LEFT JOIN assets a ON a.id = al.device_id
			WHERE al.resolved = FALSE AND al.created_at >= NOW() - INTERVAL '24 hours'
			GROUP BY al.source, al.device_id, a.asset_tag ORDER BY MAX(al.created_at) DESC LIMIT 100`)
		if err != nil {
			add(watchdogCheck{ID: "alerts", Name: "Operational alerts", Status: "error", Detail: "Operational alerts could not be read.", Action: "Check database migrations and server logs.", Href: "/security"})
		} else {
			defer rows.Close()
			count := 0
			failed := false
			for rows.Next() {
				var source, assetID, assetTag string
				var occurrences int
				if err := rows.Scan(&source, &assetID, &assetTag, &occurrences); err != nil {
					failed = true
					break
				}
				count++
				name, action, href := "Operational alert", "Review the recorded alert and verify current state before retrying.", "/security"
				switch strings.ToLower(source) {
				case "salt", "salt_patch", "patch":
					name, action, href = "Salt / patch", "Check minion identity, accepted key, VPN connectivity and Salt service. Do not repeat an unknown package operation.", "/patch"
				case "ssh", "terminal", "terminal_session":
					name, action, href = "SSH", "Check the recorded address, SSH port, server-to-device route and SSH service.", "/devices"
				case "clamav", "clam", "clamwin", "clamscan", "openscap", "open_scap", "hardening", "cve", "vulnerability":
					name = "Security scan"
				}
				if assetID != "" {
					href = "/devices/" + assetID + "/alerts"
				}
				add(watchdogCheck{ID: fmt.Sprintf("alert-%d", count), Name: name, Status: "warning", Detail: fmt.Sprintf("%s: %d unresolved alerts recorded in the last 24 hours. Current failure is not independently verified.", assetTag, occurrences), Action: action, Href: href})
			}
			if failed || rows.Err() != nil {
				add(watchdogCheck{ID: "alerts", Name: "Operational alerts", Status: "error", Detail: "Operational alert report is incomplete.", Action: "Check database connectivity and server logs.", Href: "/security"})
			} else if count == 0 {
				add(watchdogCheck{ID: "alerts", Name: "Operational alerts", Status: "ok", Detail: "No unresolved alerts recorded in the last 24 hours. This does not prove endpoint health.", Href: "/security"})
			} else if count == 100 {
				add(watchdogCheck{ID: "alerts-limit", Name: "Alert coverage", Status: "warning", Detail: "Only the 100 most recent alert groups are shown.", Action: "Review remaining alerts in their workspaces.", Href: "/security"})
			}
		}
	}
	for _, integration := range []struct {
		id, name, href string
		configured     bool
	}{
		{"salt", "Salt configuration", "/patch", strings.TrimSpace(server.config.SaltAPIBaseURL) != "" && (server.config.SaltAPIToken != "" || (server.config.SaltAPIUsername != "" && server.config.SaltAPIPassword != ""))},
		{"ssh", "SSH configuration", "/devices", strings.TrimSpace(server.config.SSHTerminalUsername) != "" && server.config.SSHTerminalPort > 0 && (server.config.SSHTerminalPrivateKeyPath != "" || server.config.SSHTerminalPrivateKey != "")},
		{"wazuh", "Wazuh configuration", "/security", server.config.WazuhAPIBaseURL != "" && server.config.WazuhAPIUsername != "" && server.config.WazuhAPIPassword != ""},
		{"inventory", "Inventory ingestion", "/devices", server.config.InventoryIngestToken != ""},
	} {
		status, detail, action := "unknown", "Configuration present; live connectivity is not verified by this report.", "Verify the integration in its workspace before deployment."
		if !integration.configured {
			status, detail, action = "warning", "Required integration configuration is missing.", "Configure this integration on the server, then verify its connection."
		}
		add(watchdogCheck{ID: integration.id, Name: integration.name, Status: status, Detail: detail, Action: action, Href: integration.href})
	}
	return report
}

func (server *apiServer) getWatchdog(c *gin.Context) {
	claims := middleware.CurrentClaims(c)
	if claims == nil || !isAdminRole(claims.Role) {
		httpx.Error(c, http.StatusForbidden, "administrator access required")
		return
	}
	c.Header("Cache-Control", "no-store")
	if server.watchdog != nil {
		httpx.JSON(c, http.StatusOK, server.watchdog.snapshot())
		return
	}
	httpx.JSON(c, http.StatusOK, server.collectWatchdog(c.Request.Context()))
}
